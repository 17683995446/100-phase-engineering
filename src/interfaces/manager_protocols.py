"""
管理器协议定义
使用 Python Protocol 定义所有管理器的抽象接口
"""
from typing import Protocol, runtime_checkable, Dict, Any, List, Optional, Callable, Set


@runtime_checkable
class ICoverageAnalyzer(Protocol):
    """覆盖率分析器接口"""

    def generate_report(self, threshold: float = 80.0) -> Any: ...
    def get_trend(self, limit: int = 10) -> List[Dict[str, Any]]: ...
    def compare_reports(self, report_id1: str, report_id2: str) -> Dict[str, Any]: ...


@runtime_checkable
class ICICDPipelineManager(Protocol):
    """CI/CD流水线管理器接口"""

    def create_pipeline(self, pipeline_id: str, name: str,
                        stages: Optional[List[Dict[str, Any]]] = None,
                        variables: Optional[Dict[str, Any]] = None,
                        triggers: Optional[List[str]] = None) -> Any: ...
    def trigger_pipeline(self, pipeline_id: str,
                         trigger: str = "manual",
                         variables: Optional[Dict[str, Any]] = None) -> Any: ...
    def run_pipeline(self, run_id: str) -> Any: ...
    def cancel_run(self, run_id: str) -> bool: ...
    def get_stats(self) -> Dict[str, Any]: ...


@runtime_checkable
class IContainerOrchestrator(Protocol):
    """容器编排管理器接口"""

    def register_service(self, service_id: str, name: str, image: str,
                         replicas: int = 1, **kwargs: Any) -> Any: ...
    def deploy_service(self, service_id: str) -> Any: ...
    def scale_service(self, service_id: str, replicas: int) -> Any: ...
    def stop_service(self, service_id: str) -> bool: ...
    def get_stats(self) -> Dict[str, Any]: ...


@runtime_checkable
class ISecretManager(Protocol):
    """密钥管理器接口"""

    def create_secret(self, name: str, secret_type: Any,
                      value: str, **kwargs: Any) -> Any: ...
    def get_secret_value(self, secret_id: str,
                         service_id: str, action: str = "read") -> Optional[str]: ...
    def rotate_secret(self, secret_id: str,
                      new_value: Optional[str] = None) -> Optional[Any]: ...
    def revoke_secret(self, secret_id: str) -> bool: ...


@runtime_checkable
class IMonitoringAlertSystem(Protocol):
    """监控告警系统接口"""

    def create_rule(self, rule_id: str, name: str, metric_name: str,
                    operator: Any, threshold: float, **kwargs: Any) -> Any: ...
    def record_metric(self, metric_name: str, value: float,
                      labels: Optional[Dict[str, str]] = None) -> None: ...
    def acknowledge_alert(self, alert_id: str, user: str) -> bool: ...
    def get_stats(self) -> Dict[str, Any]: ...


@runtime_checkable
class IConfigCenter(Protocol):
    """配置中心接口"""

    def set_config(self, key: str, value: Any, **kwargs: Any) -> Any: ...
    def get_config(self, key: str, default: Any = None) -> Any: ...
    def delete_config(self, key: str) -> bool: ...
    def subscribe(self, key: str,
                  callback: Callable[[str, Any, Any], None]) -> None: ...


@runtime_checkable
class IDataGovernancePlatform(Protocol):
    """数据治理平台接口"""

    def register_asset(self, asset_id: str, name: str, source: str,
                       **kwargs: Any) -> Any: ...
    def create_rule(self, rule_id: str, name: str, rule_type: Any,
                    asset_id: str, expression: str,
                    threshold: float = 1.0) -> Any: ...
    def evaluate_rule(self, rule_id: str, data: Any) -> Optional[Any]: ...
    def check_compliance(self, asset_id: str) -> Dict[str, Any]: ...
